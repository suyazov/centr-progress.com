<h2>Орган Управления</h2>
 
<p>Высшим коллегиальным органом управления Центром является Правление. Единоличным исполнительным органом Центра является Директор. Директор осуществляет текущее руководство деятельностью Центра и подотчетен Правлению. Контроль за финансово-хозяйственной деятельностью Центра осуществляют Учредители Центра. </p>
 
